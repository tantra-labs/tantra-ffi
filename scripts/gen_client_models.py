#!/usr/bin/env python3
"""Generate ``python/tantra/client/_models.py`` from the runtime's ``openapi.v2.json``.

Object schemas become ``TypedDict`` (``total=False``), string enums become ``Literal``
aliases, ``$ref`` maps to the schema name and anything complex maps to ``Any``.

Usage::

    python3 scripts/gen_client_models.py          # (re)generate
    python3 scripts/gen_client_models.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = (
    ROOT.parent / "tantra-runtime/crates/tantra-runtime-api-rest/schema/openapi.v2.json"
)
OUT = ROOT / "python/tantra/client/_models.py"

_SCALARS = {
    "string": "str",
    "integer": "int",
    "number": "Decimal",
    "boolean": "bool",
}


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _enum_values(schema: dict[str, Any]) -> list[str] | None:
    """Flatten a string enum (``enum`` or ``oneOf`` of single/multi-value string enums)."""
    if schema.get("type") == "string" and isinstance(schema.get("enum"), list):
        return [str(v) for v in schema["enum"]]
    one = schema.get("oneOf")
    if isinstance(one, list) and one:
        vals: list[str] = []
        for sub in one:
            sv = _enum_values(sub) if isinstance(sub, dict) else None
            if sv is None:
                return None
            vals.extend(sv)
        return vals
    return None


def _type(schema: Any, names: set[str]) -> str:
    if not isinstance(schema, dict):
        return "Any"
    if "$ref" in schema:
        n = _ref_name(schema["$ref"])
        return n if n in names else "Any"
    all_of = schema.get("allOf")
    if isinstance(all_of, list) and len(all_of) == 1:
        return _type(all_of[0], names)
    t = schema.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        if len(non_null) == 1 and len(t) == 2:
            inner = _type({**schema, "type": non_null[0]}, names)
            return inner if inner == "Any" else f"{inner} | None"
        return "Any"
    if t == "array":
        items = schema.get("items")
        return (
            f"list[{_type(items, names)}]" if isinstance(items, dict) else "list[Any]"
        )
    if t == "string":
        vals = _enum_values(schema)
        if vals:
            return "Literal[" + ", ".join(json.dumps(v) for v in vals) + "]"
        return "str"
    if isinstance(t, str) and t in _SCALARS:
        return _SCALARS[t]
    if t == "object" and not schema.get("properties"):
        return "dict[str, Any]"
    return "Any"


def _emit_object(name: str, schema: dict[str, Any], names: set[str]) -> str:
    props: dict[str, Any] = schema.get("properties") or {}
    doc = (schema.get("description") or "").strip().split("\n")[0].replace('"""', "'''")
    if all(k.isidentifier() and not keyword.iskeyword(k) for k in props):
        lines = [f"class {name}(TypedDict, total=False):"]
        if doc:
            lines.append(f'    """{doc}"""')
            lines.append("")
        for k in sorted(props):
            lines.append(f"    {k}: {_type(props[k], names)}")
        if not props:
            lines.append("    pass")
        return "\n".join(lines)
    items = ", ".join(
        f'"{k}": "{_type(props[k], names)}"'.replace("\\", "\\\\")
        for k in sorted(props)
    )
    return f'{name} = TypedDict("{name}", {{{items}}}, total=False)'


def render(schemas: dict[str, Any]) -> str:
    names = set(schemas)
    aliases: list[str] = []
    objects: list[str] = []
    for name in sorted(schemas):
        s = schemas[name]
        if not isinstance(s, dict):
            continue
        if s.get("type") == "object" and s.get("properties"):
            objects.append(_emit_object(name, s, names))
            continue
        vals = _enum_values(s)
        if vals:
            aliases.append(
                f"{name} = Literal[" + ", ".join(json.dumps(v) for v in vals) + "]"
            )
        elif s.get("type") == "object":
            aliases.append(f"{name} = dict[str, Any]")
        elif s.get("type") == "string":
            aliases.append(f"{name} = str")
        else:
            aliases.append(f"{name} = Any")
    head = (
        '"""Typed request/response models for ``/api/v2``.\n\n'
        "GENERATED by scripts/gen_client_models.py from openapi.v2.json. Do not edit.\n"
        '"""\n\n'
        "# ruff: noqa\n"
        "# fmt: off\n"
        "from __future__ import annotations\n\n"
        "from decimal import Decimal\n"
        "from typing import Any, Literal, TypedDict\n\n"
    )
    return head + "\n".join(aliases) + "\n\n\n" + "\n\n\n".join(objects) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if _models.py is stale"
    )
    ap.add_argument("--schema", type=Path, default=SCHEMA)
    args = ap.parse_args(argv)
    if not args.schema.is_file():
        print(f"schema artifact absent: {args.schema}", file=sys.stderr)
        return 0 if args.check else 2
    doc = json.loads(args.schema.read_text(encoding="utf-8"))
    text = render(doc["components"]["schemas"])
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run scripts/gen_client_models.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
